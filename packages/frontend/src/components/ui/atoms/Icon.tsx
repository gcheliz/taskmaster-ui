export interface IconProps
  extends Omit<React.HTMLAttributes<HTMLSpanElement>, 'color'>,
    VariantProps<typeof iconVariants> {
  /**
   * The icon component to render (e.g., CheckIcon, PlusIcon)
   */
  icon: React.ComponentType<React.SVGProps<SVGSVGElement>>;
  /**
   * Accessible label for the icon
   */
  'aria-label'?: string;
  /**
   * Size of the icon
   * @default 'md'
   */
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl' | '2xl';
  /**
   * Color variant of the icon
   * @default 'current'
   */
  color?: 'current' | 'primary' | 'secondary' | 'success' | 'warning' | 'error' | 'muted';
}

const Icon = React.forwardRef<HTMLSpanElement, IconProps>(
  ({ className, size, color, icon: IconComponent, 'aria-label': ariaLabel, ...props }, ref) => {
    return (
      <span
        ref={ref}
        className={cn(iconVariants({ size, color, className }))}
        aria-label={ariaLabel}
        role={ariaLabel ? 'img' : undefined}
        {...props}
      >
        <IconComponent className="h-full w-full" aria-hidden="true" />
      </span>
    );
  }
);

Icon.displayName = 'Icon';

export { Icon, iconVariants };